def senedler(url: str, xam: dict, sehifeler: list[dict]) -> dict[str, str]:
    """Yazılacaq sənədlər: {nisbi yol: məzmun}. Fayl sisteminə toxunmur."""
    return {
        "docs/research/DESIGN_TOKENS.md": _design_tokens(url, xam),
        "docs/research/COMPONENT_INVENTORY.md": _component_inventory(url, xam, sehifeler),
        "docs/research/LAYOUT_ARCHITECTURE.md": _layout_architecture(url, xam, sehifeler),
        "docs/research/INTERACTION_PATTERNS.md": _interaction_patterns(url, xam),
        "docs/research/TECH_STACK_ANALYSIS.md": _tech_stack(url, xam),
    }


def hazirla(analiz_id: int) -> dict:
    """Sənədləri `storage/klon/<domain>/` altında yazır və hazır əmri qaytarır."""
    k = kontekst.konteks(analiz_id)
    if k is None:
        return {"ugurlu": False, "tapilmadi": True, "sebeb": "Belə analiz yoxdur"}

    kok = kontekst.qovluq("klon", k["domain"])
    yazilanlar = senedler(k["url"], k["xam"], k["sehifeler"])
    yazilanlar["EMR.md"] = _emr(k["url"], str(kok))

    for nisbi, mezmun in yazilanlar.items():
        yol = kok / nisbi
        yol.parent.mkdir(parents=True, exist_ok=True)
        yol.write_text(mezmun, encoding="utf-8")

    # Köhnə ZIP qalsa istifadəçi yeni sənədləri yox, keçən dəfəkiləri yükləyər
    kohne_zip = kok.with_suffix(".zip")
    kohne_zip.unlink(missing_ok=True)

    log.info("Klon sənədləri yazıldı: %s (%s fayl)", kok, len(yazilanlar))
    return {
        "ugurlu": True,
        "qovluq": str(kok),
        "fayllar": sorted(yazilanlar),
        "emr": f"/clone-website {k['url']}",
        "cloner_yolu": ayarlar.cloner_yolu,
        "yukle_url": f"/api/analyze/{analiz_id}/yukle/klon",
    }
