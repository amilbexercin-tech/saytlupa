# ------------------------------------------------------------- kiçik köməkçilər


def _cedvel(basliqlar: list[str], setirler: list[list[str]]) -> str:
    if not setirler:
        return f"_{TAPILMADI}_\n"
    xett = "| " + " | ".join(basliqlar) + " |"
    ayirici = "|" + "|".join("---" for _ in basliqlar) + "|"
    govde = ["| " + " | ".join(str(h) for h in s) + " |" for s in setirler]
    return "\n".join([xett, ayirici, *govde]) + "\n"


def _siyahi(deyerler: list[str]) -> str:
    return "\n".join(f"- {d}" for d in deyerler) + "\n" if deyerler else f"_{TAPILMADI}_\n"


def _yoxlanmali(deyerler: list[str]) -> str:
    return "\n".join(f"- [ ] {d}" for d in deyerler) + "\n"


def _basliq(ad: str, url: str) -> str:
    tarix = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    return (
        f"# {ad}\n\n"
        f"> Auto-generated by **SaytLupa** — {tarix}\n"
        f"> Source: {url}\n"
        f"> Method: static analysis (HTML + CSS + DNS + headers). Anything that\n"
        f"> requires a rendered browser is marked `NOT DETECTED` — never guessed.\n\n"
    )


